    <!-- ABOUT -->
    <h2 id="about">About National ID</h2>

    <p>
        The National ID is an official identity document used to
        establish and verify the identity of eligible Nepali citizens.
    </p>

    <p>
        The National ID enrollment system allows applicants to provide
        their personal information, citizenship details, and supporting
        documents for verification through the appropriate office.
    </p>


    <!-- ELIGIBILITY -->
    <h2 id="eligibility">Who Can Apply?</h2>

    <p>
        Eligible Nepali citizens can submit an application through the
        National ID enrollment process.
    </p>

    <ul>
        <li>Applicant must be a Nepali citizen.</li>
        <li>Applicant must provide accurate personal information.</li>
        <li>Citizenship details must be provided correctly.</li>
        <li>Required supporting documents must be available.</li>
        <li>Additional verification may be required where applicable.</li>
    </ul>


    <!-- DOCUMENTS -->
    <h2 id="documents">Required Documents</h2>

    <p>
        Applicants should prepare the necessary documents before
        beginning the enrollment process.
    </p>

    <ul>
        <li>Valid Nepali citizenship certificate</li>
        <li>Citizenship number and related details</li>
        <li>Personal information</li>
        <li>Other supporting documents where required</li>
    </ul>

    <div class="hint">
        <strong>Important:</strong>
        Make sure that the information entered in the application
        matches the information shown on your official documents.
    </div>


    <!-- APPLICATION PROCESS -->
    <h2 id="process">Enrollment Process</h2>

    <ol>
        <li>Start your enrollment application.</li>
        <li>Enter your personal information.</li>
        <li>Provide your citizenship details.</li>
        <li>Upload your citizenship document.</li>
        <li>Review the information you entered.</li>
        <li>Submit your application.</li>
        <li>Wait for office verification.</li>
        <li>Check your application status.</li>
    </ol>


    <!-- DOCUMENT UPLOAD -->
    <h2 id="upload">Citizenship Document Upload</h2>

    <p>
        The enrollment system allows applicants to upload an image of
        their citizenship certificate for verification.
    </p>

    <ul>
        <li>Upload a clear image of your citizenship certificate.</li>
        <li>Make sure important information is visible.</li>
        <li>Avoid blurry, dark, or cropped images.</li>
        <li>Do not upload unrelated documents.</li>
    </ul>


    <!-- VERIFICATION -->
    <h2 id="verification">Office Verification</h2>

    <p>
        After submission, authorized office personnel can review the
        application information and uploaded citizenship document.
    </p>

    <details class="faq">
        <summary>
            What happens after I upload my citizenship document?
        </summary>

        <p>
            The document is stored with the application and becomes
            available for the office verification process.
        </p>
    </details>


